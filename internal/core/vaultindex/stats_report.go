package vaultindex

import (
	"cmp"
	"errors"
	"fmt"
	"path"
	"slices"
	"strings"
	"time"

	"cyberwriter/internal/core/workspace"
)

type statsRow struct {
	name  string
	count int
}

// StatsReport derives the Markdown report from saved files in the Vault.
func StatsReport(vault *workspace.Vault, name string, now time.Time) (string, error) {
	if vault == nil {
		return "", errors.New("open a Vault before generating statistics")
	}
	entries, err := vault.ReportEntries()
	if err != nil {
		return "", err
	}
	var words int
	index, err := build(vault, entries, func(note workspace.Document) {
		if note.Path != workspace.VaultStatsFile {
			words += len(strings.Fields(note.Text))
		}
	})
	if err != nil {
		return "", err
	}
	files := reportFiles(entries)
	folders, extensions := map[string]int{}, map[string]int{}
	for _, file := range files {
		parent := path.Dir(file.Path)
		if parent == "." {
			parent = "(root)"
		}
		folders[parent]++
		extensions[strings.ToLower(path.Ext(file.Name))]++
	}
	var linked, tags []statsRow
	var orphans []string
	noteCount := 0
	for _, note := range index.notes {
		if note.entry.Path == workspace.VaultStatsFile {
			continue
		}
		noteCount++
		link := reportWikilink(note.entry.Name)
		if count := len(index.wikiBacklinks[graphNoteName(note.entry.Path)]); count > 0 {
			linked = append(linked, statsRow{link, count})
		} else {
			orphans = append(orphans, link)
		}
	}
	slices.SortStableFunc(linked, func(a, b statsRow) int { return cmp.Compare(b.count, a.count) })
	slices.Sort(orphans)
	for _, tag := range index.graph.Tags {
		tags = append(tags, statsRow{"#" + tag.Name, tag.Count})
	}
	slices.SortStableFunc(tags, func(a, b statsRow) int { return cmp.Compare(b.count, a.count) })

	var report strings.Builder
	report.WriteString("---\ncyberwriter-generated: true\n---\n\n")
	fmt.Fprintf(&report, "# %s - Vault Stats\n\n", oneLine(name))
	fmt.Fprintf(&report, "Generated %s. Regenerate from the vault sidebar (📊 toolbar button) to refresh.\n", now.Format(time.RFC3339))
	writeStatsTable(&report, "Overview", "Metric", "Count", []statsRow{
		{"Files", len(files)}, {"Markdown files", noteCount}, {"Total words", words},
		{"Tags", len(index.graph.Tags)}, {"Wikilinks", index.graph.Links},
	})
	writeStatsTable(&report, "Top Tags", "Tag", "Files", tags)
	writeStatsTable(&report, "Most-linked Files", "File", "Inbound links", linked)
	if len(orphans) > 0 {
		report.WriteString("\n## Orphans\n\n_Files with no inbound wikilinks - candidates for a Map of Content entry._\n\n")
		for _, link := range orphans {
			fmt.Fprintln(&report, "-", link)
		}
	}
	if len(files) > 0 {
		slices.SortStableFunc(files, func(a, b workspace.Entry) int { return b.ModTime().Compare(a.ModTime()) })
		report.WriteString("\n## Recently Modified\n\n| File | Modified |\n| --- | --- |\n")
		for _, file := range files[:min(10, len(files))] {
			fmt.Fprintf(&report, "| %s | %s |\n", reportCell(reportWikilink(file.Name)), file.ModTime().In(now.Location()).Format("Jan 2, 2006 at 15:04"))
		}
	}
	writeStatsTable(&report, "Folders", "Folder", "Files", orderedStatsRows(folders))
	writeStatsTable(&report, "File Types", "Extension", "Count", orderedStatsRows(extensions))
	report.WriteString("\n---\n\n_Generated by cyberWriter. This file is overwritten on each regenerate - don't hand-edit it._")
	return report.String(), nil
}

func reportFiles(entries []workspace.Entry) []workspace.Entry {
	var files []workspace.Entry
	var visit func([]workspace.Entry)
	visit = func(entries []workspace.Entry) {
		for _, entry := range entries {
			if entry.IsDir {
				visit(entry.Children)
			} else if entry.Path != workspace.VaultStatsFile {
				files = append(files, entry)
			}
		}
	}
	visit(entries)
	slices.SortFunc(files, func(a, b workspace.Entry) int { return cmp.Compare(a.Path, b.Path) })
	return files
}

func reportWikilink(name string) string {
	return "[[" + oneLine(strings.TrimSuffix(name, path.Ext(name))) + "]]"
}

var reportLineBreaks = strings.NewReplacer("\r", " ", "\n", " ")

func oneLine(text string) string {
	return reportLineBreaks.Replace(strings.ToValidUTF8(text, "�"))
}

func reportCell(text string) string {
	return strings.ReplaceAll(oneLine(text), "|", `\|`)
}

func orderedStatsRows(values map[string]int) []statsRow {
	rows := make([]statsRow, 0, len(values))
	for name, count := range values {
		rows = append(rows, statsRow{name, count})
	}
	slices.SortFunc(rows, func(a, b statsRow) int {
		if a.count == b.count {
			return cmp.Compare(a.name, b.name)
		}
		return cmp.Compare(b.count, a.count)
	})
	return rows
}

func writeStatsTable(report *strings.Builder, title, first, second string, rows []statsRow) {
	if len(rows) == 0 {
		return
	}
	fmt.Fprintf(report, "\n## %s\n\n| %s | %s |\n| --- | ---: |\n", title, first, second)
	for _, row := range rows {
		fmt.Fprintf(report, "| %s | %d |\n", reportCell(row.name), row.count)
	}
}
